-- PROFILES
CREATE POLICY "Public profiles are readable by everyone"
    ON public.profiles FOR SELECT USING (true);

CREATE POLICY "Users can update own profile"
    ON public.profiles FOR UPDATE
    USING (auth.uid() = id);

-- PRODUCTS
CREATE POLICY "Products are viewable by everyone"
    ON public.products FOR SELECT USING (true);

CREATE POLICY "Only admins can modify products"
    ON public.products FOR ALL
    USING (
        EXISTS (
            SELECT 1 FROM public.profiles
            WHERE profiles.id = auth.uid() AND profiles.role = 'ADMIN'
        )
    );

-- BOOKINGS
CREATE POLICY "Members can view own bookings"
    ON public.bookings FOR SELECT
    USING (auth.uid() = member_id);

CREATE POLICY "Members can insert own bookings"
    ON public.bookings FOR INSERT
    WITH CHECK (auth.uid() = member_id);

CREATE POLICY "Admins have full booking access"
    ON public.bookings FOR ALL
    USING (
        EXISTS (
            SELECT 1 FROM public.profiles
            WHERE profiles.id = auth.uid() AND profiles.role = 'ADMIN'
        )
    );

-- CONTACTS (anonymous insert allowed)
CREATE POLICY "Anyone can submit contact form"
    ON public.contacts FOR INSERT WITH CHECK (true);

CREATE POLICY "Only admins can read contacts"
    ON public.contacts FOR SELECT
    USING (
        EXISTS (
            SELECT 1 FROM public.profiles
            WHERE profiles.id = auth.uid() AND profiles.role = 'ADMIN'
        )
    );

-- NEWSLETTERS (anonymous insert allowed)
CREATE POLICY "Anyone can subscribe newsletter"
    ON public.newsletters FOR INSERT WITH CHECK (true);

CREATE POLICY "Only admins can read newsletters"
    ON public.newsletters FOR SELECT
    USING (
        EXISTS (
            SELECT 1 FROM public.profiles
            WHERE profiles.id = auth.uid() AND profiles.role = 'ADMIN'
        )
    );

