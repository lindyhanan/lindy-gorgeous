-- 1. DEFINISI ENUM
CREATE TYPE coffee_role AS ENUM ('ADMIN', 'MEMBER', 'GUEST');
CREATE TYPE loyalty_tier AS ENUM ('SILVER', 'GOLD', 'PLATINUM');
CREATE TYPE order_status AS ENUM ('PENDING_PAYMENT', 'CONFIRMED', 'COMPLETED', 'CANCELLED');

-- 2. TABEL PROFILES (ekstensi auth.users)
CREATE TABLE public.profiles (
    id UUID REFERENCES auth.users(id) ON DELETE CASCADE PRIMARY KEY,
    full_name TEXT NOT NULL,
    role coffee_role DEFAULT 'MEMBER'::coffee_role NOT NULL,
    tier loyalty_tier DEFAULT 'SILVER'::loyalty_tier NOT NULL,
    total_points INT DEFAULT 0 NOT NULL,
    phone_number TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- 3. TABEL PRODUCTS
CREATE TABLE public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    description TEXT,
    price_base NUMERIC NOT NULL,
    stock_qty INT NOT NULL DEFAULT 100,
    image_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- 4. TABEL BOOKINGS
CREATE TABLE public.bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    product_id BIGINT REFERENCES public.products(id) ON DELETE RESTRICT,
    quantity INT DEFAULT 1 NOT NULL,
    total_final_price NUMERIC NOT NULL,
    points_credited INT DEFAULT 0 NOT NULL,
    status order_status DEFAULT 'PENDING_PAYMENT'::order_status NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- 5. TABEL CONTACTS
CREATE TABLE public.contacts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    message TEXT NOT NULL,
    is_resolved BOOLEAN DEFAULT FALSE NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- 6. TABEL NEWSLETTERS
CREATE TABLE public.newsletters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    is_active BOOLEAN DEFAULT TRUE NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- ============================================================
-- AUTO-CREATE PROFILE ON SIGNUP (TRIGGER)
-- ============================================================

-- Function: auto-create profile when user signs up
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER SET search_path = ''
AS $$
BEGIN
    INSERT INTO public.profiles (id, full_name, role, tier)
    VALUES (
        NEW.id,
        COALESCE(NEW.raw_user_meta_data->>'full_name', NEW.email),
        'MEMBER'::coffee_role,
        'SILVER'::loyalty_tier
    );
    RETURN NEW;
END;
$$;

-- Trigger: run after a new auth user is confirmed
CREATE OR REPLACE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_new_user();

